#!/usr/bin/env bash
# 32px 缺口：把"结构门筛出来的两条杠杆"交给判官，**同材质直接对判**（验证集，32px）。
#
# 为什么（承 `analysis/arch/scale_diag.py` 那轮）：32px 上 TRD 的结构门只有 28%、
# 真人 64%（p=6e-7），而尺度是对的（周期比 2.00）——**是大多数瓦片没有结构**。
# 把库里 12 个已生成的 32px 配置放进同一把门里筛，浮出两条：
#   ① 采样温度 1.0 -> 0.6：v10 一代 各向异性 0.205->0.496（p=2.4e-4）、v11d 一代 0.130->0.213（p=0.0036）；
#   ② 模型代次：补了 32px 数据的 v11d 反而最差（门 28% vs v10 的 46%、v8 的 60%）。
# ⚠ 结构门/各向异性**不是人类偏好**，拿它当优化目标必然条纹化（接缝那条路就是这么栽的）。
# 所以上面全部只算**筛选**；唯一能承认它们的方式是判官同材质直接对判（`val_judge_rr.sh` 那轮的教训：
# 各自去打第三方会把效应稀释到判不出来，配对能把 13pp/p=0.012 抬到 22pp/p=4e-4）。
#
# 两臂（都在 V_mat、32px、同材质直接对判；零 GPU，纯 API）：
#   A（决策臂）：`v10x32_t60`  vs `v11dx_direct` —— 候选新主配置（低温 + v10 一支）
#                 对现行那一支（正式测试输掉的 `TRD32_rr4` 就出自 v11d 一代）。两个因素**混在一起**，
#                 但这正是"要不要换主配置"这个决策要的那一比。
#   B（机制臂）：`v11dx_t60` vs `v11dx_direct` —— **同一个检查点，只差采样温度**，把温度单独拆出来。
#
# **预注册判据（跑之前写死，不放松）**：
#  (1) 每臂先试点（15 真题 + 5 两边同图空对照），可解率 >= 65% 且高于空对照才跑 full；
#      不过门就记"判官在这个比较上没分辨力"，**不跑 full、不找补**。
#  (2) 主判据（A 臂）：`v10x32_t60` 的胜率，二项双侧 p < 0.05 才算判出方向。
#  (3) **方向预测（写在跑之前）**：预测两臂都是 A 胜（结构门把 A 排在 B 上面）。
#      若 **A 臂打平或输**，则"结构门筛出了可用杠杆"这个读法**当场撤回**，
#      并记为"结构门不追踪判官偏好"——这正是该被写下来的那种否定结果。
#  (4) 两臂合起来读：A 胜且 B 胜 -> 温度是可迁移的杠杆，任何代次都该调；
#      A 胜而 B 打平 -> 收益归于**代次**（v11d 那次续训害了 32px），温度不是主因；
#      A 打平而 B 胜 -> 温度有用但抵不过代次差，主配置不换。
#  (5) 这**只动验证集**。据此换主配置再测测试集 = 对测试集的第二次观察，必须另行预注册后只跑一次。
#  (6) ⚠ 判官压缩效应：正结果作下界；负结果只能说"没测到大效应"。
#
# ⚠ `/mnt/data` 0 字节可用 -> 判定 JSON 全部写 `--outdir /tmp/j32`，跑完 scp 回本机入库
#   （不给 outdir 的话会**把上百次 API 调用花完、在最后一行写文件时崩**）。
# 凭据只从环境变量 VLM_BASE_URL / VLM_API_KEY 读。
set -u
P=${PY:-python}
O=${OUT:-/tmp/j32}
cd "$(dirname "$0")/.."
mkdir -p "$O"

for pair in "v10x32_t60 v11dx_direct" "v11dx_t60 v11dx_direct"; do
  set -- $pair
  echo "=== $1 vs $2 ==="
  $P eval/judge_pairs.py pilot --a "$1" --b "$2" --set V_mat --size 32 --outdir "$O" \
    && $P eval/judge_pairs.py full --a "$1" --b "$2" --set V_mat --size 32 --outdir "$O"
done
echo JUDGE32_TEMP_DONE
