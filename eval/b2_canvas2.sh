#!/usr/bin/env bash
# b2_canvas 第二次开臂：**去掉那道门**，直接跑 full。
# 预注册：本脚本先提交再跑，跑完不许改判据。零 GPU（瓦片两边都已在盘，各 272 张）。
#
# ================================================================ 为什么要重开这条臂
# 它量的是全项目 1 号缺口的分母：`658c557` 已把 (H_B2) 的**前提**坐实成构造性事实——
# `tools/downsample.py:299` 的 target_px = size/UNITS_PER_TILE 把 size 从 side=per*size/target_px
# 里约掉，于是 **side = 4.5*per，与目标尺寸无关**（`analysis/arch/b2_nyquist.py` 合成条纹实跑验证）。
# B2@16/24/32 是**同一块源区域**的三次不同密度采样，每周期分到 3.56 / 5.33 / 7.11 个输出像素。
# 也就是说"16 胜 / 24 平 / 32 输"这三档的**基线随画布单调变好，且与我们的模型无关**。
# 但这只说明增益**存在**，没说它在判官口径下**值多少**。量到之前：
#   (H_TRD) TRD 随画布变差 与 (H_B2) B2 随画布变好 **分不开** -> 32px 准入条件动不了
#   -> 一年来所有 32px 杠杆都按 (H_TRD) 设计、全灭，而 (H_TRD) 从没被单独验证过。
# 第一次开臂（`92fc3c7`）卡在 n=15 的试点门上（9/15=60% < 65%），**判据一条都没轮到**。
#
# ================================================================ 为什么是"去掉门"而不是"放宽门"
# `analysis/arch/pilot_gate_audit.py` 第二节（预注册 `bdb81a9`，结论 `c5e67a9`）量出来：
#   (M3) full 实测总体判出率 69.7%，而 65% 的门在 n=15 下要 k>=10 -> **误杀 ~28%**。
#        35 条试点里实际死了 7 条，纯噪声预测 ~10 条 -> **"不过门"这个事件几乎不携带信息。**
#   (M4) 要把误杀压到 10% 得问 120 对 —— **比它想省下的 full（272 对）还贵**。
# 门唯一的用处是省 API；当它要价比 full 还高、而且 28% 概率把健康的臂打掉时，
# **对这条臂正确的做法是不用它，而不是把线往下挪。**
#
# ⚠ 与 `c5e67a9` 那条纪律（"不许给已跑过的臂放宽门槛重跑"）的关系，说清楚不回避：
#   * 那条纪律防的是**在门上做 p-hacking**：拿到试点数字之后再挑一条能让它过的线。
#     本臂**不使用**上一次试点的 9/15 做任何决定，也**不重问**那 15 对——它被整个丢弃。
#   * **去掉一个筛子不可能引入筛选偏倚。** full 的 w 由 272 次全新提问算出（`judge_pairs.py:159-168`），
#     门只决定 full **跑不跑**。加条件才可能让 w 的分布偏移，**去条件只会让它更无条件**。
#     所以本臂报出的 w 与 p 比任何过了门的臂都更少被选择过，不是更多。
#   * 代价是真的，写在这里：①省不到 API（本臂花约 544 次调用）；②多重比较面变大（这是第 28 条臂）。
#   * 只重开**这一条**，不动 `nod32` / `B1@24`：它们是配对/对照设计，且不是 1 号缺口的分母。
#     它们的"无判决"照旧是终局。
#   * 利益冲突披露：本臂的结果可能对我们**有利**（若增益为真，三档就不能再单独当"TRD 有毛病"的证据）。
#     防串的办法是判据没改——下面 (2)(3)(4) 与 (5)-(8) 全部**逐字照抄** `92fc3c7` 的 `eval/b2_canvas.sh`，
#     包括那条对我们不利的读法。本轮只换掉 (1)。
#
# ================================================================ 设计（单臂，没有配对腿；与第一次逐字相同）
#   A = B2/32          （原生 32px：同一块源区域采到 32 个像素）
#   B = B2up16/32      （`eval/make_up2.py`：B2/16 最近邻放大 2x，同内容、密度只有一半）
# 全部 E_mat 272 材质、同材质直接对判、正反两问、opus-5——与三档逐字同协议。
#
# ================================================================ 预注册判据（跑之前写死）
#  (1') **替换掉原来的 (1)：不设试点门，可解率改由 full 自己量。**
#      full 会报 decided/272。这台仪器的可解率**地板是 17.8%**（`pilot_gate_audit.py` 第一节，
#      118 道去重空对照，判官纯按位置作答时的一致率）。
#      - 若 decided/272 **不显著高于 17.8%**（双侧二项 p >= 0.05）-> 判官在这个比较上没有分辨力，
#        **不报胜负、不下结论**（与 nod32、B1@24 同类的"什么都没测到"，不许记成"打平"）。
#      - 否则 (2)(3)(4) 生效。
#      为什么这样更好：272 对量出来的可解率比 15 对准一个数量级，而且它是**跑完之后的免费副产物**，
#      不额外花钱。门省 API 的功能本来就被 (M4) 否掉了，这里等于把它换成一个不花钱的事后检验。
#  (2) 主判据：full 上 A 的胜率 w，双侧二项检验对 50%。
#  (3) **方向预测（写在跑之前）**：预测 w 显著 > 50%。理由是内容逐像素相同、只有采样密度翻倍，
#      而 16px 那档距奈奎斯特下限只有 1.78 倍。
#  (4) 四种结果的读法**全部写在前面**，事后不许再编第五种：
#        w 显著 > 50% -> 构造性增益在判官口径下**是真的**。=> 三档**不能再单独**当作
#            "TRD 在 32px 有毛病"的证据；账本那条准入条件必须重写（怎么重写另议，本轮不改）。
#        w 不显著（跨过 50%）-> 增益虽是构造性的但**没有感知价值**。=> (H_B2) 作为三档的解释
#            死掉，准入条件原样保留，缺口确在我们这边。这是**对我们自己不利**的读法，照报。
#        w 显著 < 50% -> 判官系统性偏好采样更疏的版本。=> 这把尺子在这个问题上不可用，
#            记录后停；**不许反过来读成"16px 比 32px 好"**。
#        可解率不高于地板 -> 见 (1')，无结论。
#  (5) 口径限制（跑之前写下）：
#      - `judge_pairs.py` 的 `panel()` 把两张都 NEAREST 放到 192x192，所以 up2(B2@16) 与
#        B2@16 在判官眼里**逐像素相同**。本臂实际问的是"同一块源区域，采到 16px 还是 32px
#        更像好瓦片"，**不是**在问显示分辨率。
#      - 两档各自独立量化到 12 色，调色板可能不同。这是 B2 管线自带的性质，不是本臂引入的。
#      - 12.1% 的材质没走裁剪路径（`b2_nyquist.py` O2），对它们"同一块源内容"= 整张 1024 渲染，
#        方向一致但密度基数不同。**不分层报**，n 不够。
#  (6) **本臂不碰任何 TRD 瓦片**，两边都是 B2 自己的产物，因此**不可能泄漏进模型选型**。
#      这是它作为对测试集的第四次预注册观察仍可接受的理由（前三次：56f1801、83a6257、8ec5446）。
#  (7) **本轮不授权任何配置变更**，无论结果如何。`UNITS_PER_TILE` 一个字不改——
#      `tools/downsample.py:294` 写着"改之前必须重跑盲比"，所有已报结果都出自 4.5 的流水线。
#  (8) 操作检验（不满足则本臂作废）：`make_up2.py` 的往返断言通过；"可比对"数必须是 272；
#      `api_fail` 必须为 0；A 侧目录必须正是产生已发表 32px 那一档的 `experiments/baselines/B2/32`。
#  (9) **本轮不改 `judge_pairs.py` 的任何默认值**，包括 `min_rate=0.65`。新增的 `--no_gate`
#      必须显式传，不传则行为与今天逐字节相同；今后的臂想免门同样要各自预注册。
#
# ================================================================ 运行约束
# `/mnt/data` 满 -> 判定 JSON 写 /tmp（`scripts/sync_remote_tmp.sh` 按 judge_* 拉回本机）。
# 判官并发会互相制造 API 失败 -> 本脚本在别的 judge_pairs.py 跑着时自己等。
# 凭据只从环境变量 VLM_BASE_URL / VLM_API_KEY 读。
set -u
P=${PY:-/mnt/data/kw/anaconda3/envs/jzs_train/bin/python}
REPO=${REPO:-/mnt/data/kw/RoundSquisheen/texture}
J=${JOUT:-/tmp/judge_b2_canvas2}
cd "$REPO"
mkdir -p "$J"

# 环境探针放在等待之前：0 字节日志不该既可能是"在排队"又可能是"环境错"（val_nod32.sh 的教训）。
"$P" -c 'import numpy, PIL, sys; sys.exit(0)' || { echo "[b2_canvas2] python 探针失败: $P"; exit 1; }
[ -n "${VLM_BASE_URL:-}" ] && [ -n "${VLM_API_KEY:-}" ] || { echo "[b2_canvas2] 缺 VLM 凭据"; exit 1; }

"$P" eval/make_up2.py || { echo "[b2_canvas2] 放大或往返断言失败"; exit 1; }
for D in B2/32 B2up16/32; do
  N=$(ls "experiments/baselines/$D" 2>/dev/null | wc -l)
  [ "$N" -eq 272 ] || { echo "[b2_canvas2] $D = $N 张，不是 272"; exit 1; }
  echo "[b2_canvas2] $D = $N 张"
done

while ps -eo args | grep -q '[j]udge_pairs.py'; do
  echo "[b2_canvas2] 别的判官在跑，300s 后再看"; sleep 300
done

"$P" eval/judge_pairs.py full --no_gate --outdir "$J" --a B2 --b B2up16 --set E_mat --size 32

echo B2_CANVAS2_DONE
