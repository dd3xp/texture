#!/usr/bin/env bash
# 三档（16 胜 / 24 平 / 32 输）到底是「TRD 随画布变差」还是「B2 随画布变好」？
# 预注册：本脚本先提交再跑，跑完不许改判据。零 GPU（所有瓦片已在盘上）。
#
# ---------------------------------------------------------------- 为什么必须先问这个
# 账本给 32px 下一条臂写死的准入条件是"候选解释必须相容于三档、并能产生同材质随画布翻转"。
# 但三档的三个数字**全部是对同一个基线 B2 测的**：
#     TRD16c_rr4 vs B2@16  114/199 = 57.3% (p=0.047)
#     TRD24_rr4  vs B2@24   94/188 = 50.0% (p=1)
#     TRD32_rr4  vs B2@32   83/202 = 41.1% (p=0.014)
# `analysis/arch/tier_overlap.py` 已证明这是**逐材质效应**（同一个 v10 检查点、同一批 118 个材质，
# 24->32 翻转 18:5，p=0.011），不是子集组成的产物。但"逐材质在变"只说明**这一比**在变，
# 它**没有区分**变的是分子还是分母：
#   (H_TRD) TRD 随画布变差；          -> 账本的准入条件成立，缺口在我们这边。
#   (H_B2)  B2 随画布变好而 TRD 没变。 -> "32px 缺口"这个提法本身要改写。
# 一年来所有 32px 的杠杆（推理侧八条 + 训练侧两条 + 换数据来源）都是按 (H_TRD) 设计的，
# 全灭。(H_B2) 从未被测过，而它有直接的机制理由：
#   `docs/arch_progress.md:36` B1 = SDXL + 降采样、B2 = 现有管线（同样是**高分辨率渲染再降采样**）。
#   把 1024px 渲染降到 32px 比降到 16px **必然**保留更多结构，像素越多越忠实 —— 这是降采样这一族
#   的构造性性质，与我们的模型无关。TRD 与 B7 则是在目标画布上**原生生成**，没有这个免费增益。
# 这也正是 `edge` 那把尺子看到、但当时只当中性描述记下的东西：32px 上 B2 的逐像素密度掉到 0.656
# 而 TRD 只到 0.765（16px 两者同为 0.797/0.803）——**变的那一边是 B2**。
#
# ---------------------------------------------------------------- 设计（四条臂，唯一变量 = 基线族）
# 用**同一批 TRD 瓦片**（就是产生上面三档的那些目录，逐字节相同）去对两个**不同族**的基线：
#   B1 = SDXL + 降采样      -> 与 B2 同族（降采样族）。**正对照**。
#   B7 = 同数据从零训练的像素空间扩散 UNet（`baselines/ddpm_unet.py`）-> 原生生成，非降采样。**锚**。
#   P24  TRD24_rr4 vs B7 @24      P32  TRD32_rr4 vs B7 @32
#   Q24  TRD24_rr4 vs B1 @24      Q32  TRD32_rr4 vs B1 @32
# 全部 E_mat 272 材质、同材质直接对判、正反两问、opus-5 —— 与三档逐字同协议。
#
# ---------------------------------------------------------------- 预注册判据（跑之前写死）
#  (1) 每条臂先试点（15 真题 + 5 两边同图的空对照）：可解率 >= 65% 且高于空对照才跑 full。
#      不过门槛 = 判官在这个比较上没有分辨力，该臂**不报胜负**，且它所属的那一对梯度作废。
#      （这台仪器的可解率地板实测约 16%，`analysis/arch/pilot_gate_audit.py`。）
#  (2) **主判据 = 梯度，不是胜率本身**。对每个基线，在它 24 与 32 两条臂**共同判出**的材质上做
#      McNemar（口径与 `analysis/arch/tier_overlap.py` 逐字相同，那里 B2 得到 18:5、p=0.011）：
#        - 对 B1 的 24->32 翻转显著（p<0.05）且方向是 24 赢得多  =: "对 B1 下滑"
#        - 对 B7 同上                                          =: "对 B7 下滑"
#  (3) **方向预测（写在跑之前）**：预测 **对 B1 下滑、对 B7 不下滑**，即 (H_B2)。
#  (4) 四种结果的读法**全部写在前面**，事后不许再编第五种：
#        对 B1 下滑 + 对 B7 不下滑 -> (H_B2)。"32px 缺口"改写为"降采样族随画布拿到免费增益"，
#            账本的准入条件作废重写。**本轮仍不改任何配置**（见 (7)）。
#        两个都下滑             -> (H_TRD)。准入条件原样保留，缺口确在我们这边。
#        两个都不下滑           -> B2 在三个基线里是特例；两个假设都不成立，记录后停，
#            **不许事后再编一个关于 B2 的故事**。
#        对 B7 下滑但对 B1 不    -> 预测被推翻，且"降采样族"作为一个族的说法同时死掉。
#  (5) ⚠ 口径限制（跑之前写下）：**B7 在 24/32 上从未调过 CFG**。CFG 扫描（1.5/3/5）只在 16px 做过
#      （`experiments/eval_b7cfg_Vmat_16.json`），测试集 B7 三个尺寸用同一设置。这是给 B7 的一个
#      未知方向的让步，但它**在 24 与 32 上完全相同**，因此**造不出梯度**，只能整体平移两条臂的水平。
#      -> 所以只判梯度；**对 B7 的绝对胜率照实报出但不进任何判据**。B1 无此问题（SDXL 无尺寸超参）。
#  (6) ⚠ 已知的识别弱点（跑之前写下，防止事后往有利方向读）：B7 与 TRD 训练在**同一个数据池**上，
#      所以若那 641 张 32px 数据本身是坏的，B7@32 会一起变差、对 B7 的梯度会被抹平。
#      -> **"对 B7 不下滑"与 (H_B2) 相容，但不等于证明了 (H_B2)**。B1 正是为此而在设计里：
#      SDXL 从未碰过我们的数据，它那条梯度不受这个弱点影响。结论必须由 B1 与 B7 **合读**。
#  (7) **本轮不授权任何配置变更**，无论结果如何。这是诊断，不是选型；三档的 TRD 瓦片一个字不动。
#  (8) 操作检验（不满足则该臂作废）：四条臂的"可比对"数必须都是 272，且 `api_fail` 必须为 0；
#      A 侧目录必须正是 `TRD24_rr4/24` 与 `TRD32_rr4/32`（产生已发表三档的同一批文件）。
#  (9) 这是对测试集的**第三次**预注册观察（前两次：正式测试 56f1801、16px 消融 83a6257）。
#      非用测试集不可的理由：三档是测试集上的事实，要问"变的是分子还是分母"就必须用**同一批材质、
#      同一批 TRD 瓦片**；换到 V_mat 既不可比（另一批材质、另一批臂），n 也只有约 80，
#      McNemar 的不一致对会掉到十几个，根本判不动梯度。
#
# ---------------------------------------------------------------- 运行约束
# `/mnt/data` 满 -> 判定 JSON 全部写 /tmp（`scripts/sync_remote_tmp.sh` 按 judge_* 拉回本机）。
# 判官并发会互相制造 API 失败 -> 本脚本在别的 judge_pairs.py 跑着时自己等（arch_nod32 的判官在排队）。
# 零 GPU：四条臂用的瓦片全部已在 experiments/baselines/ 下，不生成任何新图。
# 凭据只从环境变量 VLM_BASE_URL / VLM_API_KEY 读。
set -u
P=${PY:-/mnt/data/kw/anaconda3/envs/jzs_train/bin/python}
REPO=${REPO:-/mnt/data/kw/RoundSquisheen/texture}
J=${JOUT:-/tmp/judge_tier_anchor}
cd "$REPO"
mkdir -p "$J"

# 环境探针放在等待之前：0 字节日志不该既可能是"在排队"又可能是"环境错"（val_nod32.sh 的教训）。
"$P" -c 'import numpy, json, sys; sys.exit(0)' || { echo "[tier_anchor] python 探针失败: $P"; exit 1; }
[ -n "${VLM_BASE_URL:-}" ] && [ -n "${VLM_API_KEY:-}" ] || { echo "[tier_anchor] 缺 VLM 凭据"; exit 1; }
for D in TRD24_rr4/24 TRD32_rr4/32 B1/24 B1/32 B7/24 B7/32; do
  N=$(ls "experiments/baselines/$D" 2>/dev/null | wc -l)
  [ "$N" -gt 0 ] || { echo "[tier_anchor] 缺瓦片目录 $D"; exit 1; }
  echo "[tier_anchor] $D = $N 张"
done

wait_judge() {
  while ps -eo args | grep -q '[j]udge_pairs.py'; do
    echo "[tier_anchor] 别的判官在跑，300s 后再看"; sleep 300
  done
}

J1() {   # 试点不过门就跳过 full，但不终止其余臂（每条臂的判读是独立的）
  wait_judge
  "$P" eval/judge_pairs.py pilot --outdir "$J" "$@" || { echo "[tier_anchor] 试点不过门，跳过 full"; return 0; }
  wait_judge
  "$P" eval/judge_pairs.py full --outdir "$J" "$@"
}

J1 --a TRD24_rr4 --b B7 --set E_mat --size 24
J1 --a TRD32_rr4 --b B7 --set E_mat --size 32
J1 --a TRD24_rr4 --b B1 --set E_mat --size 24
J1 --a TRD32_rr4 --b B1 --set E_mat --size 32

echo TIER_ANCHOR_DONE
