# =====================================================================================
# (M41) 预注册：**训练侧 CLIP 目标** —— 账本里唯一一条从没试过的架构侧杠杆
# 本文件在任何权重/图像/判定存在之前提交 = 预注册。跑完不许改判据、不许改配方重跑。
# =====================================================================================
#
# ------------------------------------------------------------------- (1) 为什么是这条
# 2026-09-12 起，账本每一轮的"下一步"里都挂着同一句、且一直没人做：
#   「训练侧的 CLIP 杠杆（把 CLIP 相似度做进训练目标而非条件）仍是唯一不在这条曲线上的方向。」
# 那条"曲线"是量到的汇率：**CLIP 每涨约 1.1，FD 涨约 16–22**，而两条已知杠杆
# （挑调色板先验 = 跨模态检索；挑最终样本 = 4 选 1 重排）**是同一笔买卖**
# （CLIP≈34.6 这点上 FD 104.7 vs 110.6，差 5.7 而门槛 19 ⇒ 分不出）。
# ⇒ 已知的一切都只在曲线上滑动，没有一条把曲线整体推出去。
# `--align_clip`（v6）是把对齐分数当**条件**，只动了 ±0.2；本轮把它当**梯度**。
#
# 与"推理侧八条旋钮已全否"的关系（照 (M37) 的写法，说清楚不回避）：那八条是**作为 32px 缺口的
# 杠杆**被否的，且全在推理侧；本条在训练侧、且判据全在 16px。
# ⛔ **无论结果如何都不许把本轮任何数字搬到 24/32px**（32px 准入条件④：尺子没校准）。
#
# ------------------------------------------------------------------- (2) 臂与唯一变量
#   A = clipw：v8 last.pt 续训 6000 步，**加**训练侧 CLIP 对齐损失
#   B = ctl  ：完全相同的续训，**不加**该损失
# 唯一变量 = `--clip_loss/--clip_w/--clip_bs` 这三个标志。其余逐字相同。
# ⚠ B 不是 v8 本身，也不是 v10：(M40) 已判 v10 vs v8 `GEN_NULL`，且 v10 还动了 p32
#   ⇒ 只有自己训一条同配方控制臂，A−B 之差才**只**归因于这个损失。
# 成对配方（(M29)–(M33)）：`--init_from` + `--reseed_after_build` 缺一不可
#   —— ClipAlign 在 `seed_for_training` **之前**构造，故两臂进循环时 CPU/GPU RNG 状态相同。
# 续训超参照抄 v10 那次成功的续训（lr 1.5e-4、warmup 500），只把 `--sizes` 收成 16
# （判据全在 16px；⛔ 由此产生的模型**不许出货到 24/32px**）、且不开 `--coarse`（v8 没有那个模块）。
#
# ------------------------------------------------------------------- (3) 损失长什么样（写死）
# 可微路径 = 结构 logits 的 softmax × 该样本自己的**真调色板** = 期望图；
# 被掩的格子取软的、没被掩的取真值且 detach ⇒ 梯度只从"模型自己预测的格子"流回去。
# 最近邻放大到 224 → 冻结 CLIP 图像塔 → 与 "pixel art texture of {材质}" 的余弦。
# ⚠⚠ 故意用**第三个** CLIP（L/14）：评测用 B/32、重排用 B/16。
# ⛔ **CLIP 分数本身不是本轮任何一条判据** —— 即使它涨了也只当"损失确实在起作用"的操作检验，
#    ⛔ 不许当成质量证据（Goodhart）。⛔ 也不许事后改用 B/32 重测来让数字好看。
#
# ------------------------------------------------------------------- (4) 操作检验（跑完逐条核，任一不过 ⇒ 判 VOID）
# (OP1) 两臂 `config.json` 除 clip_loss/clip_w/clip_bs/out 外逐键相同。
# (OP2) 两臂 step 0 的 `loss_grid` 与 `loss_pal` 相同（到 1e-5）＝ 第 0 步取到的是同一批、同一套掩码
#       ⇒ 成对种子真的生效。⚠ 不用 step0 的 `val` 查这件事：两臂都刚从同一个 `last.pt` 载入，
#       val 必然相同，那一条**对成对性没有任何信息量**（本预注册写死时差点犯这个错，记在此处）。
# (OP3) A 的日志里 `clip_cos` 单调区间上升（首 500 步均值 < 末 500 步均值）＝ 损失确实在被优化。
#       ⚠ 这一条**只**用来确认"损失通了"，⛔ 不是效应证据。
# (OP4) 两臂都跑满 6000 步、都有 `last.pt`。
# (OP5) 生成阶段：A、B 的 125 张成图**同图对 ≤ 25/125**（照 (M37)(M38)(M40) 已用的门）。
# (OP6) 判官 `api_fail == 0`；开跑前先 curl 探针一次（(M40) 的教训：失效 key 会静默烧掉一小时）。
#
# ------------------------------------------------------------------- (5) 零 API 筛子：本轮**当门用**，并据此预注册
# (M40) 说得很清楚：那把 pixfrac 筛子三点同向、且做出过一次未被证伪的样本外预测，
# **要当门用必须另行预注册、锚点换成现在这三个**。本文件就是那次预注册。
# 三锚点（逐字照抄，⛔ 不许改）：
#     D37 = 0.8173（ck3k vs ck20k，判官**显著**）
#     D38 = 0.6608（cfg25 vs cfg15，`CFG_NULL`）
#     D40 = 0.6431（gen10 vs gen8，`GEN_NULL`）
# 门（跑生成之后、花 API 之前算，一次）：
#     d ≥ 0.8173            -> `SCREEN_GO`   ：开判官臂。
#     d ≤ 0.6608            -> `SCREEN_NOGO` ：**不开判官臂、不花 API**，本轮判 `CLIPLOSS_TOO_SMALL`
#                              并如实记"这个损失没把产物推开多远"。
#     0.6608 < d < 0.8173   -> `SCREEN_AMBIGUOUS`：照 (M39) 原样 —— **不开判官臂**，记账走人。
# ⚠ 这是筛子第一次被真的当门用。若判 GO 且判官随后**显著**，那就是它第一个**独立**的 GO 验证
#   （D37 是用来定门槛的那一点，不算）。若判 GO 而判官 NULL ⇒ **筛子被证伪**，当场写下并撤回它。
# ⛔ 事后不许换尺子（(M39) 已记：同一份数据 `mae` 给的次序相反）、⛔ 不许挪门槛。
#
# ------------------------------------------------------------------- (6) 判官臂与判据（只在 `SCREEN_GO` 时执行）
# 配方逐字照抄 (M37)(M38)(M40) 用的 TRD16c：16px / V_mat / `--cfg 1.5` /
# `--pal_mode retrieve --xmodal --ret_nname 100` / `--n 4` + `rerank.py --n 4` / `--no_gate`。
# 主判据 = **族级 (U1) CI**（`judge_cluster.analyse`，`recheck_judge.EXPECT` 登记新臂后跑）：
#     CI 不含 0.5 且偏 A -> `CLIPLOSS_WINS`（训练侧 CLIP 目标是一条活杠杆）
#     CI 不含 0.5 且偏 B -> `CLIPLOSS_HURTS`（同样是结论：这条杠杆是负的，当场关掉）
#     CI 含 0.5           -> `CLIPLOSS_NULL`
# ⛔ `_NULL` 的读法只有一条：**在该 n 上没测到 ≥X% 的效应**（X 按实得 n 精确二项现算）。
#    ⛔ 不许读成"没差别"、⛔ 不许读成"一样好"。
# ⚠⚠ **功效**：(M40) 实测可解率 63.2% → 56.0% → 50.4% 在往下掉，n=63 时门槛已要 63.5%。
#    本轮换的是**整个训练目标**（不是旋钮），若它有用就该是大效应；若可解率仍掉到 50% 左右
#    且 CI 含 0.5，⛔ 不许靠加臂碰运气，按 (M40) 的话去解决功效本身。
# 次要报告项（⛔ 非判据，thr(1)=KID 4.656 / FID 6.0 / FD 20 / CLIP 0.41）：`run_eval.py` 四项。
#
# ------------------------------------------------------------------- (7) 跑前预测（写死，跑完照录，推翻了就照录推翻）
# (P1) 筛子 d(A,B) **≥ 0.8173**（`SCREEN_GO`）：换的是整个训练目标、且从第 0 步就改梯度，
#      产物差别应当大于"换整副权重续训 12000 步"的 0.6431。
# (P2) 若开成判官臂：预测 `CLIPLOSS_WINS`。理由 = (1) 里那条汇率论证。
# (P3) A 的 `val`（16px 交叉熵）**会比 B 差**：加了一个与似然无关的目标。
#      ⚠ 若 A 的 val 更差而判官更好，那正是 (M37) 已量到的"val 曲线在这件事上指错方向"的第二例；
#      ⛔ 但 val 不是本轮判据，⛔ 不许拿它挑检查点（(M37) `CKPT_LATE_WINS`：出货一律 `last.pt`）。
#
# ------------------------------------------------------------------- (8) 不许动的东西
# ⛔ `eval/final_test.sh` 一个字不许改 —— 只有判出 `CLIPLOSS_WINS` 才**授权另行预注册**一次换配置；
#    ⛔ 本轮无论如何都不许直接改它。
# ⛔ `judge_pairs.py`（活件）、`judge_cluster*.py`、`UNITS_PER_TILE`、任何默认值、
#    32px 准入条件①②③④、已下的任何判决，全部不动。
# ⛔ 结构门 / 各向异性永远不许当优化目标或挑配置的依据。
# =====================================================================================
set -e
cd "$(dirname "$0")/.."
PY=${PY:-python}
export HF_HUB_OFFLINE=1
export TRITON_CACHE_DIR=${TRITON_CACHE_DIR:-/tmp/triton_m41}
TAG=${TAG:?必须显式传 TAG（MMDDHHmm），否则无法把两臂钉在同一次启动上}
A=runs/trd_clipw_$TAG
B=runs/trd_ctl_$TAG

COMMON="--init_from runs/trd_v8/last.pt --reseed_after_build --seed 0 \
 --sizes 16 --steps 6000 --batch 256 --lr 1.5e-4 --warmup 500 --eval_every 500 \
 --codes 512 --extra --extra_file train_extra_packs_only.json \
 --n_ex 4 --level_emb --bias_freqs 8"

case "${1:-}" in
  A) exec $PY model/train_trd.py --out $A $COMMON \
       --clip_loss openai/clip-vit-large-patch14 --clip_w 0.3 --clip_bs 32 ;;
  B) exec $PY model/train_trd.py --out $B $COMMON ;;
  *) echo "用法：TAG=MMDDHHmm CUDA_VISIBLE_DEVICES=n bash $0 {A|B}" >&2; exit 2 ;;
esac
