#!/usr/bin/env bash
# 环的第四条边：**判官在跨画布尺寸上到底可不可加**。
# 预注册：本脚本先提交再跑，跑完不许改判据。零 GPU（两边瓦片都已在盘，各 272 张）。
#
# ================================================================ 它在测什么（先说清它**不**测什么）
# `557a50e` 量到 B2@32 打赢 B2@16 = 107/138 = 78%。把它和已发表的两档放在一起，
# 四个产物之间就有**四条边、构成一个环**（`analysis/arch/tier_cycle.py`）：
#
#         TRD@16  --e1: 114/199=57%-->  B2@16
#           |                             |
#         e4: ?                         e3: 107/138=78%
#           v                             v
#         TRD@32  --e2:  83/202=41%-->  B2@32
#
# Bradley-Terry 下 logit 胜率可加，于是 **e4 被前三条边完全决定**：d4 = d2 + d3 - d1。
# 也就是说，e4 **不带来新的自由度**——它是一个**点预测**，因此是对这台仪器的
# **传递性/可加性检验**，而不是一次新的比较。这是本臂的主判据。
#
# ⚠ **它不是"TRD 的画布增益"**：`eval/final_test.sh:18,22` 写着 TRD16c 出自 **v8**、
#   TRD32 出自 **v10**（`--ret_nname` 都是 100，4 选 1 也都在）。d4 = 画布 + 代次，捆在一起。
#   → 可以说"**我们交付的产物**从 16px 档到 32px 档变好了多少"（缺口问的正是交付物）；
#     **不可以**说成"TRD 从画布拿到多少增益"。可加性检验本身不受这个混淆影响
#     ——它检验的是判官对这四个**具体产物**是否传递，与产物怎么来的无关。
#
# ================================================================ 为什么这件事值得花 544 次调用
# 「16 胜 / 24 平 / 32 输」是全项目的 1 号缺口，一年来所有 32px 杠杆都按它设计、全灭。
# 但把三档**并排读成一条随画布下降的曲线**，本身就预设了三个尺寸的比较落在同一把尺子上。
# **这个前提从没验过。** 若环不闭合，则三档根本不能并排读，"32px 缺口"这个提法要重做——
# 那比再开一条杠杆重要得多。若环闭合，则 `tier_cycle.py` 的分解可以当结论用：
# 两边**都**随画布变好、只是 B2 变得更快，于是 (H_TRD)「TRD 随画布变差」的原始形式是假的。
#
# ================================================================ 设计（单臂，没有配对腿）
#   A = TRD32_rr4/32     （产生已发表 32px 那一档的**同一批文件**，一个字不改）
#   B = TRD16cup/32      （`eval/make_up2.py` 把 TRD16c_rr4/16 最近邻放大 2x）
# 全部 E_mat 272 材质、同材质直接对判、正反两问、opus-5——与三档逐字同协议。
#
# ================================================================ 预注册判据（跑之前写死）
#  (1) **免门，理由与 `557a50e` 逐字相同**：去掉一个筛子不可能引入筛选偏倚（full 的 w 由 272 次
#      全新提问算出，门只决定跑不跑）。可解率改由 full 自己量：报 decided/272，对**实测地板 17.8%**
#      （`pilot_gate_audit.py`，118 道去重空对照）做双侧二项检验。
#      不显著高于地板 -> 判官没分辨力、**不报胜负、不下结论**（与 nod32、B1@24 同类，不许记成"打平"）。
#      本臂**不跑试点**，也**没有**旧试点数字可用。
#  (2) **主判据 = 点预测检验**。`tier_cycle.py`（与本脚本同一提交）在**两把尺子**上各给一个预测：
#        (S1) 只算判出（与已发表三档同口径）：**预测 64.2%，95% 预测区间 [50.5%, 75.9%]**
#        (S2) inconsistent 记 0.5 分、分母固定 272：**预测 52.3%，95% 预测区间 [44.0%, 60.6%]**
#      为什么必须两把：四条边的判出率差得很远（e1 73%、e2 74%、**e3 只有 51%**），而丢掉平局会把
#      logit 往外推、判出率越低推得越狠——e3 恰是判出率最低、logit 最大的那条，**这正是该假象的方向**。
#      两把尺子只在一把上闭合，就不算闭合。
#  (3) **方向预测（写在跑之前）**：预测 e4 的实测点**同时**落在 (S1) 与 (S2) 的预测区间内，
#      且 w > 50%（我们的交付物在 32px 档比在 16px 档更好）。
#  (4) 四种结果的读法**全部写在前面，事后不许再编第五种**：
#        两把尺子都落在区间内 -> **环闭合**，可加性成立。=> `tier_cycle.py` 的分解可以当结论用：
#            两边都随画布变好、B2 变得更快。**(H_TRD) 的原始形式（TRD 随画布变差）判死**，
#            32px 准入条件按残差形式重写（见 (4b)）。
#        只在一把尺子上落进区间 -> **结论不稳**：三档的读数依赖弃样口径本身。
#            记录、**不判死 (H_TRD)**、准入条件原样保留；下一步是修弃样口径（怎么修另议），不是开杠杆。
#        两把都落在区间**下方**（含 w 不显著异于 50%、或显著 < 50%）-> 我们的产物从 16px 档到
#            32px 档**没有变好**。=> 环不闭合，但方向与 (H_TRD) 一致：缺口确在我们这边。
#            这是**对我们自己不利**的读法，照报；准入条件原样保留。
#        两把都落在区间**上方** -> 我们的产物涨得比环允许的还多 -> 判官跨尺寸**不可加**，
#            三档不能并排读。=> 记录后停，**不许反过来读成"我们其实没输"**。
#        可解率不高于地板 -> 见 (1)，无结论。
#  (4b) 若 (4) 判死 (H_TRD) 原始形式，准入条件重写为：候选解释必须说清**为什么多给的像素
#      在我们手里换来的质量比一个降采样器还少**，并同时兼容三档 + e3 + e4 四个读数。
#      **本轮不据此开任何 32px 新臂**；重写只改账本里那句话。
#  (5) 口径限制（跑之前写下）：
#      - `panel()` 把两张都 NEAREST 放到 192x192，所以 up2(TRD16c_rr4) 与 TRD16c_rr4 在判官眼里
#        **逐像素相同**。本臂问的是"我们 16px 档的交付物和 32px 档的交付物，哪个更像好瓦片"，
#        **不是**在问显示分辨率。
#      - 两档各自有自己的调色板与 4 选 1 重排（两边**都**是 rr4，所以重排不是两边的差别）。
#      - (L3) 的 v8/v10 混淆见上，**不分层报**，也**不许**声称已隔离画布。
#  (6) **两边都是我们自己已发表的产物，不引入任何新配置**，因此不可能泄漏进模型选型。
#      这是它作为对测试集的**第五次**预注册观察仍可接受的理由（前四次：56f1801、83a6257、
#      8ec5446、557a50e）。多重比较面变大是真实代价，写在这里。
#  (7) **本轮不授权任何配置变更**，无论结果如何。`UNITS_PER_TILE` 与 `final_test.sh` 一个字不改。
#  (8) 操作检验（不满足则本臂作废）：`make_up2.py` 的往返断言通过；"可比对"数必须是 272；
#      `api_fail` 必须为 0；A 侧目录必须正是产生已发表 32px 那一档的 `experiments/baselines/TRD32_rr4/32`。
#  (9) **不改 `judge_pairs.py` 的任何默认值**。`--no_gate` 显式传。
#
# ================================================================ 运行约束
# `/mnt/data` 满 -> 判定 JSON 写 /tmp（`scripts/sync_remote_tmp.sh` 按 judge_* 拉回本机）。
# 判官并发会互相制造 API 失败 -> 本脚本在别的 judge_pairs.py 跑着时自己等。
# 凭据只从环境变量 VLM_BASE_URL / VLM_API_KEY 读。
set -u
P=${PY:-/mnt/data/kw/anaconda3/envs/jzs_train/bin/python}
REPO=${REPO:-/mnt/data/kw/RoundSquisheen/texture}
J=${JOUT:-/tmp/judge_trd_canvas}
cd "$REPO"
mkdir -p "$J"

# 环境探针放在等待之前：0 字节日志不该既可能是"在排队"又可能是"环境错"（val_nod32.sh 的教训）。
"$P" -c 'import numpy, PIL, sys; sys.exit(0)' || { echo "[trd_canvas] python 探针失败: $P"; exit 1; }
[ -n "${VLM_BASE_URL:-}" ] && [ -n "${VLM_API_KEY:-}" ] || { echo "[trd_canvas] 缺 VLM 凭据"; exit 1; }

"$P" eval/make_up2.py TRD16c_rr4/16 TRD16cup/32 || { echo "[trd_canvas] 放大或往返断言失败"; exit 1; }
for D in TRD32_rr4/32 TRD16cup/32; do
  N=$(ls "experiments/baselines/$D" 2>/dev/null | wc -l)
  [ "$N" -eq 272 ] || { echo "[trd_canvas] $D = $N 张，不是 272"; exit 1; }
  echo "[trd_canvas] $D = $N 张"
done

while ps -eo args | grep -q '[j]udge_pairs.py'; do
  echo "[trd_canvas] 别的判官在跑，300s 后再看"; sleep 300
done

"$P" eval/judge_pairs.py full --no_gate --outdir "$J" --a TRD32_rr4 --b TRD16cup --set E_mat --size 32

echo TRD_CANVAS_DONE
