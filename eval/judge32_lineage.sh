#!/usr/bin/env bash
# 承 `eval/judge32_temp.sh` 两臂的结果，把**代次**单独拆出来（验证集 32px，同材质直接对判）。
#
# 那两臂（同一轮，已跑完）：
#   A  `v10x32_t60` vs `v11dx_direct`：32/74 = **43%**，p=0.295 -> **打平**（预注册的方向预测落空）
#   B  `v11dx_t60`  vs `v11dx_direct`（同检查点，只差温度）：21/80 = **26%**，**p=2.53e-05**
#      -> 低温**显著更差**，与结构门的排序**正好相反**（门说 t60 更好：39% vs 28%、各向异性 0.213 vs 0.130）。
# 按 judge32_temp.sh 的判据 (3)，"结构门筛出了可用杠杆"这个读法已**当场撤回**。
#
# 但 A 打平这件事本身还留了一个可测的推论：A 臂 = 代次(v10 vs v11d) + 温度(0.6 vs 1.0)，
# 而 B 臂量到温度那一项值 **-24pp**。若两项近似可加，则代次那一项必须是 **+约 20pp** 才能让 A 打平
# -> **预测 `v10x_direct` 显著胜 `v11dx_direct`**。
# ⚠ 这条预测来自两臂的算术，**不来自结构门**（门刚被证明在温度轴上与判官反向，不可再当依据）；
#    且三臂的可解子集不同，可加性只是近似，所以这是一条**可证伪的预测**，不是推导出来的结论。
#
# **预注册判据（跑之前写死）**：
#  (1) 试点（15 真题 + 5 空对照）可解率 >= 65% 且高于空对照，才跑 full。
#  (2) 主判据：`v10x_direct` 胜率二项双侧 p < 0.05。
#  (3) 方向预测：**v10x_direct 胜**。若打平或输 -> 上面那条可加性推论**当场撤回**，
#      并记为"32px 上判官对 TRD 各配置之间没有可利用的偏好"，下一轮不再在已有配置里挑，改动架构/训练。
#  (4) 赢了也只动验证集：换 32px 主配置后再测测试集 = 对测试集的第二次观察，必须另行预注册后只跑一次。
#  (5) ⚠ 判官压缩效应：正结果作下界。
#
# ⚠ `/mnt/data` 0 字节可用 -> `--outdir /tmp/j32`。凭据只从环境变量读。
set -u
P=${PY:-python}
O=${OUT:-/tmp/j32}
cd "${REPO:-$(dirname "$0")/..}"
mkdir -p "$O"

$P eval/judge_pairs.py pilot --a v10x_direct --b v11dx_direct --set V_mat --size 32 --outdir "$O" \
  && $P eval/judge_pairs.py full --a v10x_direct --b v11dx_direct --set V_mat --size 32 --outdir "$O"
echo JUDGE32_LINEAGE_DONE
