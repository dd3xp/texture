#!/usr/bin/env bash
# B2 随画布拿到的那个**构造性**增益，在判官口径下到底值多少？
# 预注册：本脚本先提交再跑，跑完不许改判据。零 GPU（只是把已在盘的 B2@16 最近邻放大）。
#
# ---------------------------------------------------------------- 为什么必须问这一条
# 三档（16 胜 57.3% / 24 平 50.0% / 32 输 41.1%）全部是对同一个基线 B2 测的。`8ec5446` 把它
# 拆成 (H_TRD) TRD 随画布变差 与 (H_B2) B2 随画布变好，`eval/tier_anchor.sh` 想用 B1/B7 两族
# 基线把两者分开，结果 B1@24 卡在 n=15 的试点门上、整对梯度作废（`d0345de`）。
#
# 但 `analysis/arch/b2_nyquist.py` 这一轮**实跑**（不是读代码）证明了 (H_B2) 的前提：
#   auto_crop 的裁剪边长 side = 4.5 * per，**与目标尺寸无关**（target_px = size/UNITS_PER_TILE
#   把 size 约掉了）。三个周期 16/32/64px 的合成图上，16/24/32 三档给出逐字节相同的 side。
#   -> B2@16 / B2@24 / B2@32 是**同一块源区域**的三次不同密度采样，
#      每个结构周期分到 3.56 / 5.33 / 7.11 个输出像素（距奈奎斯特下限 1.78x / 2.67x / 3.56x）。
#      覆盖率：272 个测试材质里 86.8% 走了这条裁剪路径。
# 也就是说**分母随画布单调变好是构造性的、与我们的模型无关**。但这只说明增益存在，
# **没说它在判官口径下值多少**——可能是 80% 的压倒性优势，也可能一点都看不出来。
# 这个量一旦测出来，三档还能不能当作"TRD 在 32px 有毛病"的证据，答案就变了。
#
# ---------------------------------------------------------------- 设计（单臂，没有配对腿）
#   A = B2/32          （原生 32px：同一块源区域采到 32 个像素）
#   B = B2up16/32      （`eval/make_up2.py`：B2/16 最近邻放大 2x，同内容、密度只有一半）
# 全部 E_mat 272 材质、同材质直接对判、正反两问、opus-5——与三档逐字同协议。
# **刻意做成单臂**：`d0345de` 的教训是配对设计里任意一条腿挂掉整对就作废（一对存活只有 (1-q)^2）。
# 这个问题不需要配对——它是 B2 管线内部的自问自答。
#
# ---------------------------------------------------------------- 预注册判据（跑之前写死）
#  (1) 试点（15 真题 + 5 两边同图的空对照）：可解率 >= 65% 且高于空对照才跑 full。
#      不过门 = 判官在这个比较上没有分辨力，**不报胜负、不下结论**（与 nod32、B1@24 同类：
#      "什么都没测到"，不许记成"打平"）。
#  (2) 主判据：full 上 A 的胜率 w，双侧二项检验对 50%。
#  (3) **方向预测（写在跑之前）**：预测 w 显著 > 50%。理由是内容逐像素相同、只有采样密度翻倍，
#      而 16px 那档距奈奎斯特下限只有 1.78 倍。
#  (4) 四种结果的读法**全部写在前面**，事后不许再编第五种：
#        w 显著 > 50% -> 构造性增益在判官口径下**是真的**。=> 三档**不能再单独**当作
#            "TRD 在 32px 有毛病"的证据；账本那条准入条件必须重写（怎么重写另议，本轮不改）。
#        w 不显著（跨过 50%）-> 增益虽是构造性的但**没有感知价值**。=> (H_B2) 作为三档的解释
#            死掉，准入条件原样保留，缺口确在我们这边。这是**对我们自己不利**的读法，照报。
#        w 显著 < 50% -> 判官系统性偏好采样更疏的版本。=> 这把尺子在这个问题上不可用，
#            记录后停；**不许反过来读成"16px 比 32px 好"**。
#        试点不过门 -> 见 (1)，无结论。
#  (5) 口径限制（跑之前写下）：
#      - `judge_pairs.py` 的 `panel()` 把两张都 NEAREST 放到 192x192，所以 up2(B2@16) 与
#        B2@16 在判官眼里**逐像素相同**。本臂实际问的是"同一块源区域，采到 16px 还是 32px
#        更像好瓦片"，**不是**在问显示分辨率。
#      - 两档各自独立量化到 12 色，调色板可能不同。这是 B2 管线自带的性质，不是本臂引入的。
#      - 12.1% 的材质没走裁剪路径（`b2_nyquist.py` O2），对它们"同一块源内容"= 整张 1024 渲染，
#        方向一致但密度基数不同。**不分层报**，n 不够。
#  (6) **本臂不碰任何 TRD 瓦片**，两边都是 B2 自己的产物，因此**不可能泄漏进模型选型**。
#      这是它作为对测试集的第四次预注册观察仍可接受的理由（前三次：56f1801、83a6257、8ec5446）。
#  (7) **本轮不授权任何配置变更**，无论结果如何。`UNITS_PER_TILE` 一个字不改——
#      `tools/downsample.py:294` 写着"改之前必须重跑盲比"，所有已报结果都出自 4.5 的流水线。
#  (8) 操作检验（不满足则本臂作废）：`make_up2.py` 的往返断言通过；"可比对"数必须是 272；
#      `api_fail` 必须为 0；A 侧目录必须正是产生已发表 32px 那一档的 `experiments/baselines/B2/32`。
#
# ---------------------------------------------------------------- 运行约束
# `/mnt/data` 几乎满 -> 判定 JSON 写 /tmp（`scripts/sync_remote_tmp.sh` 按 judge_* 拉回本机）。
# 瓦片本身只有约 100KB，写回 experiments/baselines/ 下（判官只从那里读）。
# 判官并发会互相制造 API 失败 -> 本脚本在别的 judge_pairs.py 跑着时自己等。
# 凭据只从环境变量 VLM_BASE_URL / VLM_API_KEY 读。
set -u
P=${PY:-/mnt/data/kw/anaconda3/envs/jzs_train/bin/python}
REPO=${REPO:-/mnt/data/kw/RoundSquisheen/texture}
J=${JOUT:-/tmp/judge_b2_canvas}
cd "$REPO"
mkdir -p "$J"

# 环境探针放在等待之前：0 字节日志不该既可能是"在排队"又可能是"环境错"（val_nod32.sh 的教训）。
"$P" -c 'import numpy, PIL, sys; sys.exit(0)' || { echo "[b2_canvas] python 探针失败: $P"; exit 1; }
[ -n "${VLM_BASE_URL:-}" ] && [ -n "${VLM_API_KEY:-}" ] || { echo "[b2_canvas] 缺 VLM 凭据"; exit 1; }

"$P" eval/make_up2.py || { echo "[b2_canvas] 放大或往返断言失败"; exit 1; }
for D in B2/32 B2up16/32; do
  N=$(ls "experiments/baselines/$D" 2>/dev/null | wc -l)
  [ "$N" -eq 272 ] || { echo "[b2_canvas] $D = $N 张，不是 272"; exit 1; }
  echo "[b2_canvas] $D = $N 张"
done

while ps -eo args | grep -q '[j]udge_pairs.py'; do
  echo "[b2_canvas] 别的判官在跑，300s 后再看"; sleep 300
done

"$P" eval/judge_pairs.py pilot --outdir "$J" --a B2 --b B2up16 --set E_mat --size 32 \
  || { echo "[b2_canvas] 试点不过门，按判据 (1) 不跑 full、不报胜负"; echo B2_CANVAS_DONE; exit 0; }

while ps -eo args | grep -q '[j]udge_pairs.py'; do
  echo "[b2_canvas] 别的判官在跑，300s 后再看"; sleep 300
done

"$P" eval/judge_pairs.py full --outdir "$J" --a B2 --b B2up16 --set E_mat --size 32

echo B2_CANVAS_DONE
